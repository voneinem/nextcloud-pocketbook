#pragma once
// Chunked upload v2 (specs/002-manage-server-files, contracts/server-requests.md W4, research R-4): a large file goes to the server in chunks of
// 10 MiB in an upload folder of its own, is assembled by one final MOVE, and an interrupted upload continues by listing that folder. The
// upload folder is the app's own temporary session under /dav/uploads/, not user data: its MKCOL, chunk PUTs and DELETE carry no condition
// (constitution Principle III, plan.md Complexity Tracking). This file and dav_write.cpp/queue_sender.cpp are the only ones that name write methods
// (rule N2). Server behaviour is UNVERIFIED (docs/live-server-checklist.md LV-W5 to LV-W7). Qt-free.

#include <cstdint>
#include <optional>
#include <set>
#include <string>
#include <string_view>

#include "pbc/dav_common.h"
#include "pbc/dav_write.h"
#include "pbc/store_files.h"
#include "pbc/types.h"

namespace pbc {

inline constexpr int kMaxChunks = 10000;

struct ChunkPlan {
    int64_t total = 0;
    int64_t chunk_size = 0;
    int count = 0;
    int64_t offset_of(int n) const { return static_cast<int64_t>(n - 1) * chunk_size; }            // chunks are numbered from 1
    int64_t size_of(int n) const { return n < count ? chunk_size : total - static_cast<int64_t>(count - 1) * chunk_size; }
};

// `nullopt` for an empty file, a chunk size of zero, or more than kMaxChunks chunks.
std::optional<ChunkPlan> plan_chunks(int64_t total, int64_t chunk_size);
// "00001" ... "10000": zero-padded, because the server assembles in name order and "10" would sort before "2".
std::string chunk_name(int n);

struct UploadFolder {
    std::set<int> good;   // chunks whose name is in range and whose size is the expected one
    int bad = 0;          // chunks of the wrong size (to be sent again)
    bool gone = false;    // the upload folder does not exist (never made, or expired after 24 hours)
};
// A PROPFIND Depth 1 answer of the upload folder. Hostile names, names out of range, duplicates and entries that are not chunks are ignored; a truncated
// or partial answer yields what could be read. Errors: malformed_xml, protocol_error (not a 207), listing_too_large.
Result<UploadFolder> parse_upload_folder(const Response& propfind, const ChunkPlan& plan);

class UploadSession {
public:
    // `upload_id` names the upload folder (generated by the caller and stored in the queue row before the first request); `destination` is the
    // remote path of the final file; `mtime` and `checksum` (SHA-256 hex) of the source go into the headers of the final MOVE.
    UploadSession(DavSession& session, std::string user_id, std::string upload_id, std::string destination, ChunkPlan plan, std::string checksum, int64_t mtime);

    WriteAnswer open();                                                    // MKCOL of the upload folder
    Result<UploadFolder> list();                                           // PROPFIND of the upload folder, Depth 1
    // PUT of chunk n from the byte range of the source file
    WriteAnswer send_chunk(int n, const std::string& source_path, ProgressFn progress);
    // The final MOVE of .file onto the destination: new (Overwrite: F) or replace (Overwrite: T and If-Match: replace_etag)
    WriteAnswer assemble(bool replace, const std::string& replace_etag);
    WriteAnswer abort();                                                   // DELETE of the upload folder

    std::string folder_url() const;

private:
    DavSession& session_;
    std::string user_id_, id_, destination_, checksum_;
    ChunkPlan plan_;
    int64_t mtime_;
};

}  // namespace pbc
